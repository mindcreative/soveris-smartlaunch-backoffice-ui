import { readFile, mkdir, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import Ajv from 'ajv'
import Ajv2020 from 'ajv/dist/2020.js'
import addFormats from 'ajv-formats'
import standaloneCode from 'ajv/dist/standalone/index.js'
import ts from 'typescript'

const root = new URL('../', import.meta.url)
const check = process.argv.includes('--check')
const generatedNotice = '// Generated by scripts/generate-csp-validators.mjs; do not edit.\n'

async function json(relative) {
  return JSON.parse(await readFile(new URL(relative, root), 'utf8'))
}

async function save(relative, contents) {
  const destination = new URL(relative, root)
  const expected = generatedNotice + contents + '\n'

  if (check) {
    if (await readFile(destination, 'utf8') !== expected) {
      throw new Error('Standalone validators are stale; run the generator.')
    }

    return
  }

  await mkdir(fileURLToPath(new URL('./', destination)), { recursive: true })
  await writeFile(destination, expected)
}

const product = new Ajv2020({ allErrors: true, coerceTypes: false, removeAdditional: false,
  strict: true, useDefaults: false, code: { source: true } })
addFormats(product)
const draft = await json('src/contracts/product-content/v1/product-content.schema.json')
const publish = await json('src/contracts/product-content/v1/product-content-publish.schema.json')
product.addSchema(await json('src/contracts/product-content/v1/form-profile.schema.json'))
product.addSchema(draft)
product.addSchema(publish)
await save('src/contracts/product-content/generated/validators.cjs', standaloneCode(product, {
  draftValidator: draft.$id, publishValidator: publish.$id,
}))
await save('src/contracts/product-content/generated/validators.d.cts',
  "import type { ValidateFunction } from 'ajv'\nexport const draftValidator: ValidateFunction\nexport const publishValidator: ValidateFunction")

// Transpile the pure existing schema definitions with the installed compiler.
// This avoids a Node-version-specific TypeScript loader or another package.
const schemaSource = await readFile(new URL('src/contracts/reconciliation/schema.ts', root), 'utf8')
const compiled = ts.transpileModule(schemaSource, {
  compilerOptions: { target: ts.ScriptTarget.ES2020, module: ts.ModuleKind.ESNext }, reportDiagnostics: true,
})

if (compiled.diagnostics?.some(diagnostic => diagnostic.category === ts.DiagnosticCategory.Error)) {
  throw new Error('Reconciliation schema compilation failed.')
}

const schema = await import('data:text/javascript;base64,' + Buffer.from(compiled.outputText).toString('base64'))
const reconciliation = new Ajv({ strict: true, code: { source: true } })
addFormats(reconciliation)
reconciliation.addSchema(schema.ReconciliationPageSchema, 'reconciliation-page')
reconciliation.addSchema(schema.ReconciliationResolutionSchema, 'reconciliation-resolution')
await save('src/contracts/reconciliation/generated/validators.cjs', standaloneCode(reconciliation, {
  validateReconciliationPage: 'reconciliation-page', validateReconciliationResolution: 'reconciliation-resolution',
}))
await save('src/contracts/reconciliation/generated/validators.d.cts',
  "import type { ValidateFunction } from 'ajv'\nimport type { ReconciliationPage, ReconciliationResolution } from '../../../types/reconciliation'\n" +
  'export const validateReconciliationPage: ValidateFunction<ReconciliationPage>\nexport const validateReconciliationResolution: ValidateFunction<ReconciliationResolution>')
